package io.github.puflik.plinth.core.config

/**
 * Откуда приложение берёт ключи внешних API.
 *
 * Различие между сборками, а не настройка пользователя: в `github`-сборке
 * ключи зашиты на этапе компиляции, в F-Droid этого сделать нельзя —
 * там воспроизводимая сборка из открытых исходников, и ключ пришлось бы
 * опубликовать вместе с ними.
 */
enum class ApiKeySource {
    /** Ключ подставлен в `BuildConfig` при сборке. */
    BUILD_CONFIG,

    /** Ключ вводит пользователь в настройках. */
    USER_PROVIDED,
}
