package io.github.puflik.plinth.audio.engine

/**
 * Что показать о треке за пределами приложения (E2): уведомление, экран
 * блокировки, гарнитура и часы с экраном.
 *
 * Приложение знает о треке больше, чем его теги: у файла без тегов название —
 * имя файла. Движок отдаёт эти подписи системе, а поля, которых нет, система
 * берёт из тегов самого файла.
 */
data class TrackInfo(
    val title: String?,
    val artist: String? = null,
    val album: String? = null,
)
