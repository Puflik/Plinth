package io.github.puflik.plinth.queue

/**
 * Действия долгого нажатия на трек (D1.2). Обычное касание — «играть в
 * контексте» ([PlaybackQueue.play]); «заменить очередь» — то же, но без
 * ручных добавлений ([PlaybackQueue.replace]).
 */
enum class QueueAction {
    /** В начало ручного блока: сыграет сразу после текущего. */
    PLAY_NEXT,

    /** В конец ручного блока: после уже добавленного, до продолжения контекста. */
    ADD_TO_QUEUE,
}

/** Повтор (D1.4). */
enum class RepeatMode {
    OFF,

    /** По кругу — контекст; ручные треки однократны. */
    ALL,

    /** Текущий трек сам по себе играет заново; пропустить его можно. */
    ONE,
}
