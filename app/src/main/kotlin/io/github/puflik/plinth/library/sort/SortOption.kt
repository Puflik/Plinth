package io.github.puflik.plinth.library.sort

/**
 * Порядок списка треков (C4.3). Названия сравниваются [ключами][SortKeys];
 * треки без исполнителя или альбома идут в конце, равные — по `id`.
 */
enum class TrackSort {
    /** По названию, затем по исполнителю. */
    TITLE,

    /** По исполнителю, внутри — по альбомам, диску и номеру трека. */
    ARTIST,

    /** По альбому и его владельцу, внутри — по диску и номеру трека. */
    ALBUM,
}

/**
 * Порядок списка альбомов (C4.3). Альбомы без владельца идут в конце.
 * Исполнители сортируются только по имени — своего варианта у них нет.
 */
enum class AlbumSort {
    /** По названию, затем по владельцу. */
    TITLE,

    /** По владельцу, затем по названию. */
    ARTIST,
}
