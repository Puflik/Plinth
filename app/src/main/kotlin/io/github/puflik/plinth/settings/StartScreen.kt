package io.github.puflik.plinth.settings

/**
 * Настройка «Стартовый экран» (F3, план 12.6): умолчание — [AUTO].
 * «Открытия» появятся вместе с вкладкой открытий (v0.9).
 */
enum class StartScreen {
    /** Решают правила: пустая библиотека, недавняя игра, перерыв. */
    AUTO,

    /** Всегда библиотека. */
    LIBRARY,

    /** Всегда плеер с той же очередью — если что-то уже играло. */
    CONTINUE,
}
